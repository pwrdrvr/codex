#!/usr/bin/env python3

import importlib.util
from pathlib import Path
import shutil
import tempfile
import unittest


SCRIPT = Path(__file__).with_name("stamp-workspace-version.py")
SPEC = importlib.util.spec_from_file_location("stamp_workspace_version", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
STAMP = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(STAMP)


MANIFEST = """[workspace]
members = ["models-manager", "cli"]
resolver = "2"

[workspace.package]
version = "0.0.0"
edition = "2024"

[workspace.dependencies]
codex-models-manager = { path = "models-manager" }
serde = { version = "1" }
"""

LOCKFILE = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "codex-cli"
version = "0.0.0"
dependencies = [
 "codex-models-manager",
]

[[package]]
name = "codex-models-manager"
version = "0.0.0"

[[package]]
name = "vendored-local"
version = "0.0.0"

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""

MEMBERS = ("codex-cli", "codex-models-manager")


class StampWorkspaceVersionTest(unittest.TestCase):
    def test_manifest_stamps_only_the_workspace_package_version(self) -> None:
        stamped = STAMP.stamp_manifest(MANIFEST, "0.171.0")
        self.assertEqual(STAMP.workspace_package_version(stamped), "0.171.0")
        self.assertIn('serde = { version = "1" }', stamped)
        self.assertEqual(STAMP.stamp_manifest(stamped, "0.171.0"), stamped)

    def test_manifest_version_may_follow_arrays_and_comments(self) -> None:
        manifest = MANIFEST.replace(
            '[workspace.package]\nversion = "0.0.0"\n',
            '[workspace.package]\n# see [docs]\nauthors = ["a"]\nversion = "0.0.0"\n',
        )
        self.assertEqual(STAMP.workspace_package_version(manifest), "0.0.0")
        stamped = STAMP.stamp_manifest(manifest, "0.171.0")
        self.assertEqual(STAMP.workspace_package_version(stamped), "0.171.0")
        self.assertIn('authors = ["a"]', stamped)

    def test_manifest_version_is_not_taken_from_a_later_table(self) -> None:
        manifest = '[workspace.package]\nedition = "2024"\n\n[package]\nversion = "9.9.9"\n'
        with self.assertRaises(STAMP.StampError):
            STAMP.workspace_package_version(manifest)

    def test_manifest_without_workspace_package_version_is_rejected(self) -> None:
        with self.assertRaisesRegex(STAMP.StampError, r"\[workspace\.package\]"):
            STAMP.stamp_manifest('[workspace]\nmembers = []\n', "0.171.0")

    def test_lockfile_stamps_only_named_local_members(self) -> None:
        stamped = STAMP.stamp_lockfile(LOCKFILE, MEMBERS, "0.171.0")
        self.assertEqual(
            STAMP.local_lockfile_versions(stamped),
            {
                "codex-cli": "0.171.0",
                "codex-models-manager": "0.171.0",
                "vendored-local": "0.0.0",
            },
        )
        # The lockfile format version and registry packages are untouched.
        self.assertIn("\nversion = 4\n", stamped)
        self.assertIn('name = "serde"\nversion = "1.0.0"', stamped)
        self.assertEqual(STAMP.stamp_lockfile(stamped, MEMBERS, "0.171.0"), stamped)

    def test_lockfile_preserves_crlf(self) -> None:
        crlf = LOCKFILE.replace("\n", "\r\n")
        stamped = STAMP.stamp_lockfile(crlf, MEMBERS, "0.171.0")
        self.assertEqual(stamped, STAMP.stamp_lockfile(LOCKFILE, MEMBERS, "0.171.0").replace("\n", "\r\n"))

    def test_lockfile_missing_member_is_rejected(self) -> None:
        with self.assertRaisesRegex(STAMP.StampError, "codex-missing"):
            STAMP.stamp_lockfile(LOCKFILE, MEMBERS + ("codex-missing",), "0.171.0")

    def test_upstream_version_must_be_plain_non_placeholder_semver(self) -> None:
        with tempfile.TemporaryDirectory() as temporary_directory:
            path = Path(temporary_directory) / "upstream-version.txt"
            path.write_text("0.171.0\n", encoding="utf-8")
            self.assertEqual(STAMP.read_upstream_version(path), "0.171.0")
            for invalid in ("0.0.0", "0.171.0-alpha.9", "0.171", ""):
                path.write_text(f"{invalid}\n", encoding="utf-8")
                with self.assertRaises(STAMP.StampError, msg=invalid):
                    STAMP.read_upstream_version(path)

    def test_release_version_must_be_based_on_upstream_version(self) -> None:
        for release_version in (
            "0.171.0",
            "0.171.0-pwragent.5",
            "0.171.0-pwragent.dev.42",
        ):
            STAMP.check_release_version(release_version, "0.171.0")
        for release_version in ("0.172.0-pwragent.1", "0.171.01-pwragent.1", "0.17.0"):
            with self.assertRaises(STAMP.StampError, msg=release_version):
                STAMP.check_release_version(release_version, "0.171.0")

    @unittest.skipUnless(shutil.which("cargo"), "cargo is not installed")
    def test_stamp_then_verify_against_a_real_cargo_workspace(self) -> None:
        with tempfile.TemporaryDirectory() as temporary_directory:
            workspace = Path(temporary_directory)
            (workspace / "Cargo.toml").write_text(
                '[workspace]\nmembers = ["models-manager", "cli", "app-server",'
                ' "code-mode-host", "pinned"]\nresolver = "2"\n\n'
                '[workspace.package]\nversion = "0.0.0"\nedition = "2021"\n',
                encoding="utf-8",
            )
            lock = ["version = 4"]
            crates = {
                "models-manager": "codex-models-manager",
                "cli": "codex-cli",
                "app-server": "codex-app-server",
                "code-mode-host": "codex-code-mode-host",
            }
            for directory, name in crates.items():
                self._crate(workspace, directory, name, "version.workspace = true")
                lock.append(f'[[package]]\nname = "{name}"\nversion = "0.0.0"')
            # A member with its own version must not be rewritten.
            self._crate(workspace, "pinned", "pinned", 'version = "0.0.0"')
            lock.append('[[package]]\nname = "pinned"\nversion = "0.0.0"')
            (workspace / "Cargo.lock").write_text(
                "\n\n".join(lock) + "\n", encoding="utf-8"
            )

            with self.assertRaisesRegex(STAMP.StampError, "0.0.0"):
                STAMP.verify(workspace, "0.171.0")
            STAMP.stamp(workspace, "0.171.0")
            STAMP.verify(workspace, "0.171.0")
            self.assertEqual(
                STAMP.local_lockfile_versions(
                    (workspace / "Cargo.lock").read_text(encoding="utf-8")
                )["pinned"],
                "0.0.0",
            )
            STAMP.cargo_metadata(workspace)  # still loads after stamping

            # A stamped manifest with a stale lockfile still fails verify.
            lockfile = workspace / "Cargo.lock"
            lockfile.write_text(
                lockfile.read_text(encoding="utf-8").replace(
                    'name = "codex-models-manager"\nversion = "0.171.0"',
                    'name = "codex-models-manager"\nversion = "0.0.0"',
                ),
                encoding="utf-8",
            )
            with self.assertRaisesRegex(STAMP.StampError, "codex-models-manager.*Cargo.lock"):
                STAMP.verify(workspace, "0.171.0")

            # Any other inheriting member left stale also fails verify.
            STAMP.stamp(workspace, "0.171.0")
            self._crate(workspace, "otel", "codex-otel", "version.workspace = true")
            manifest = workspace / "Cargo.toml"
            manifest.write_text(
                manifest.read_text(encoding="utf-8").replace('"pinned"]', '"pinned", "otel"]'),
                encoding="utf-8",
            )
            with lockfile.open("a", encoding="utf-8") as handle:
                handle.write('\n[[package]]\nname = "codex-otel"\nversion = "0.0.0"\n')
            with self.assertRaisesRegex(STAMP.StampError, "codex-otel.*Cargo.lock"):
                STAMP.verify(workspace, "0.171.0")

    @staticmethod
    def _crate(workspace: Path, directory: str, name: str, version: str) -> None:
        crate = workspace / directory
        (crate / "src").mkdir(parents=True)
        (crate / "src/lib.rs").write_text("", encoding="utf-8")
        (crate / "Cargo.toml").write_text(
            f'[package]\nname = "{name}"\n{version}\nedition = "2021"\n',
            encoding="utf-8",
        )


if __name__ == "__main__":
    unittest.main()
